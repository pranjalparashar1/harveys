// Derives Pierre's 2-class technique prior from pranjal's rated rows (v2 Step 3).
//   node scripts/derive-prior.mjs        rewrites src/brain/technique-prior.js
// For each technique in PRIOR_TECHNIQUES and each food class, the effect is the mean,
// rounded, of (cooked row − raw rating) over every rated food@technique of that class,
// and the distance is the rounded median. Nothing is typed in: re-run after each ingest.
// Every entry is provisional: a rated row or a dish verdict always beats it.
import { writeFileSync } from 'node:fs';
import { PIERRE_RAW } from '../src/brain/pierre-raw.js';
import { TEXTURES, TASTES } from '../src/brain/ingredients.js';

export const PRIOR_TECHNIQUES = ['air_fried', 'pan_fried', 'sauteed'];

export function derivePrior(kb = PIERRE_RAW) {
  const out = {};
  for (const tech of PRIOR_TECHNIQUES) {
    const byClass = {};
    for (const [key, row] of Object.entries(kb.tech ?? {})) {
      const [id, t] = key.split('@');
      const raw = kb.foods?.[id];
      if (t !== tech || !raw?.class || row.veto) continue;
      (byClass[raw.class] ??= []).push({ id, raw, row });
    }
    for (const [cls, rows] of Object.entries(byClass)) {
      const mean = (f) => Math.round(rows.reduce((s, r) => s + f(r), 0) / rows.length) || 0; // no -0
      const ds = rows.map((r) => r.row.distance).sort((a, b) => a - b);
      (out[tech] ??= {})[cls] = {
        texture: Object.fromEntries(TEXTURES.map((k) => [k, mean((r) => (r.row.texture[k] ?? 0) - (r.raw.texture[k] ?? 0))])),
        taste: Object.fromEntries(TASTES.map((k) => [k, mean((r) => (r.row.taste[k] ?? 0) - (r.raw.taste[k] ?? 0))])),
        distance: ds[Math.floor((ds.length - 1) / 2)],
        from: rows.map((r) => r.id).sort(),
        provisional: true,
      };
    }
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const prior = derivePrior();
  const file = new URL('../src/brain/technique-prior.js', import.meta.url);
  writeFileSync(file, `// GENERATED by scripts/derive-prior.mjs from the rated rows in pierre-raw.js. Don't edit:
// re-run the script after an ingest. PROVISIONAL (v2 Step 3): a 2-class prior on few rows
// (\`from\` lists them). Used only when a food@technique has no rated row of its own.
export const TECHNIQUE_PRIOR = ${JSON.stringify(prior, null, 2).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'")};\n`);
  for (const [t, cs] of Object.entries(prior)) for (const [c, e] of Object.entries(cs)) console.log(`${t} ${c}: n=${e.from.length} (${e.from.join(', ')})`);
}
